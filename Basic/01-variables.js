//var

var helloWorld = 'Hola mundo'
//Almaceno en memoria el valor de una cadena de texto y luego la utilizo
console.log(helloWorld)

helloWorld = "Hola de nuevo, mundo"
console.log(helloWorld)

//De esta manera NO se usan las variables en JS

//let

let helloWorld2 = 'Hola mundo 2'
console.log(helloWorld2)

helloWorld2 = "Hola JavaScript"
console.log(helloWorld2)

//const

const helloWorld3 = 'Hola mundo 3'
console.log(helloWorld3)
//No puedes reescribir una variable const, puesto que usando const el valor de la variable va a ser CONSTANTE
